#列表的方法和函数很多，包括两种排列，我们跳过
i0=[]#空列表
#方法append
i0.append('1号')
print(i0[0])#在最后一个后面加一个，由于这里是空列表，所以就加在了第一个
#想修改直接改下标
i0[0]='一号'
print(i0[0])
#方法insert(下标，插入值)插入
i0[1]='3号'
i0.insert(1,'2号')#注意，这样子会使i0【1】后面所有的往后挪一个，给1号腾出位子插入新数值
print(i0[1],i0[2])
#我们发现输出的二号和三号
#del删除函数
del(i0[1])#删除后不可以访问，而且后面的都会往前挪一个
print(i0[1])#发现是三号
#方法pop弹出值
i0[2]='4号'
i1=i0.pop(2)#下标写后面，如果不写默认是最后一个
#注意，做完如上操作后，i0的四号会消失，但保存到了i1里面
#如果不知道下标，只知道数值，我们就可以用remove操作
#方法remove
i=[1,2,3]
i.remove(2)#这里2的意思是删除2这个值
print(i[0],i[1])#发现只有1和3
#len函数确认长度
long=len(i)
print(long)#是2
print(i[-1])#打印倒数第一个
print(i[-2])#打印倒数第二个
